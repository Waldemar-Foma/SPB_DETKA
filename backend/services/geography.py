def region_info(prefix: str):
    return REGIONS.get((prefix or "")[:2], (f"Регион РФ {(prefix or '')[:2] or '—'}", 55.75, 37.62))


def region_from_kpp(kpp: str) -> str:
    return region_info(kpp)[0]


def region_center(region: str) -> tuple[float, float]:
    raw = (region or "").strip()
    normalized = raw.lower().replace("ё", "е")
    if normalized in CITY_ALIASES:
        return CITY_ALIASES[normalized]
    for name, lat, lon in REGIONS.values():
        if name.lower().replace("ё", "е") == normalized:
            return lat, lon
    # Accept inputs like "Казань, Республика Татарстан" or "г. Москва".
    for city, coords in CITY_ALIASES.items():
        if city in normalized:
            return coords
    for name, lat, lon in REGIONS.values():
        if name.lower().replace("ё", "е") in normalized:
            return lat, lon
    return 55.75, 37.62


def approx_supplier_coords(inn: str, region: str) -> tuple[float, float]:
    lat, lon = region_center(region)
    digest = hashlib.sha256(str(inn).encode("utf-8")).digest()
    a = int.from_bytes(digest[:4], "big") / 2**32 - .5
    b = int.from_bytes(digest[4:8], "big") / 2**32 - .5
    # Небольшой jitter, чтобы маркеры компаний одного региона не лежали строго друг на друге.
    return round(lat + a * .55, 5), round(lon + b * .85, 5)


def distance_km(a: tuple[float, float], b: tuple[float, float]) -> int:
    lat1, lon1, lat2, lon2 = map(math.radians, [a[0], a[1], b[0], b[1]])
    dlat, dlon = lat2 - lat1, lon2 - lon1
    h = math.sin(dlat / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin(dlon / 2) ** 2
    return round(6371 * 2 * math.asin(math.sqrt(h)))


def logistics_score(procurement, supplier) -> dict:
    text = " ".join(str(x or "") for x in [procurement.title, procurement.subject, procurement.okpd2_name, procurement.keywords]).lower()
    delivery = getattr(procurement, "delivery_region", None) or getattr(procurement, "region", None) or "Санкт-Петербург"
    origin = getattr(supplier, "region", None) or "Россия"
    dist = distance_km(region_center(delivery), region_center(origin))

    if any(x in text for x in DIGITAL_HINTS):
        profile, soft_limit, hard_limit = "remote", 8000, 12000
    elif any(x in text for x in PERISHABLE_HINTS):
        profile, soft_limit, hard_limit = "perishable", 250, 900
    elif any(x in text for x in BULKY_HINTS):
        profile, soft_limit, hard_limit = "bulky", 700, 2200
    elif any(x in text for x in SERVICE_LOCAL_HINTS) or getattr(procurement, "procurement_kind", None) in {"works"}:
        profile, soft_limit, hard_limit = "local_service", 350, 1300
    else:
        profile, soft_limit, hard_limit = "general", 1500, 5000

    if dist <= soft_limit:
        score = 100
    elif dist >= hard_limit:
        score = 10
    else:
        score = round(100 - 90 * ((dist - soft_limit) / (hard_limit - soft_limit)))

    if profile == "remote":
        note = "Расстояние почти не влияет на выполнение этого запроса."
    elif score >= 80:
        note = f"Логистика выглядит разумно: примерно {dist:,} км до региона исполнения.".replace(",", " ")
    elif score >= 45:
        note = f"Расстояние около {dist:,} км. Стоит отдельно проверить сроки и стоимость доставки.".replace(",", " ")
    else:
        note = f"Около {dist:,} км до региона исполнения. Для этой категории логистика может сделать предложение невыгодным.".replace(",", " ")

    return {"score": max(0, min(100, score)), "distance_km": dist, "profile": profile, "note": note}
